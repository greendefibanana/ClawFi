export function buildDemoTreasury(config = demoStrategyConfig): Treasury {
  const totalValueUsd = basePositions.reduce((sum, position) => sum + position.valueUsd, 0);
  const liquidValueUsd = basePositions
    .filter((position) => position.assetType !== "yield_position")
    .reduce((sum, position) => sum + position.valueUsd, 0);

  return treasurySchema.parse({
    treasuryId: "treasury-clawfi-primary",
    accountId: "0.0.7001001",
    network: "testnet",
    mode: "simulated",
    portfolio: {
      positions: basePositions,
      totalValueUsd,
      liquidValueUsd,
    },
    budgets: {
      reserveBudgetUsd: totalValueUsd * (config.reservePercent / 100),
      tradingBudgetUsd: totalValueUsd * (config.tradingPercent / 100),
      defiBudgetUsd: totalValueUsd * (config.defiPercent / 100),
      rewardBudgetUsd: 1450,
      executionBudgetUsd: 380,
    },
    idleStablecoinUsd: 150000,
    reserveCoveragePercent: (150000 / (totalValueUsd * (config.reservePercent / 100))) * 100,
  });
}

